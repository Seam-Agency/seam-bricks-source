export function resolveSeamBricksTheme(theme: SeamBricksTheme): SeamBricksSceneTheme {
  if (typeof theme === "string") return { ...SEAM_BRICKS_SCENE_THEMES[theme] };
  return { ...SEAM_BRICKS_SCENE_THEMES.paper, ...theme };
}

export function mergeMaterialPalette(
  base: SeamBricksMaterialPalette,
  overrides: SeamBricksMaterialPaletteOverrides = {},
): SeamBricksMaterialPalette {
  return {
    ...base,
    ...overrides,
    frontClosed: [...(overrides.frontClosed ?? base.frontClosed)],
    frontOpen: [...(overrides.frontOpen ?? base.frontOpen)],
    bottom: [...(overrides.bottom ?? base.bottom)],
    peg: [...(overrides.peg ?? base.peg)],
  };
}
